def vinca_pinning(distro: str) -> str:
    """shared/pinning/conda_forge.yaml + overrides.yaml, adjusted by distro.yaml.

    Shared override entries that the distribution overrides itself are left out
    together with the comment lines above them (comments carry the conda-build
    selectors, so this works on text, not on parsed YAML).
    """
    s = settings(distro)
    own = s.get("pinning_overrides") or {}
    out = [f"# Generated by `pixi run rs {distro} render-pinning` from shared/pinning/ and",
           f"# distros/{distro}/distro.yaml; edit those instead.", ""]
    if s.get("conda_forge_pinning_version"):
        out.append(f"conda_forge_pinning_version: {s['conda_forge_pinning_version']}")
        out.append("migrations:")
        out += [f"  - {m}" for m in s.get("conda_forge_migrations") or []]
    else:
        out += [l for l in (SHARED / "pinning" / "conda_forge.yaml").read_text().splitlines()
                if not l.startswith("#")]
    comments: list[str] = []
    skip = False
    for line in (SHARED / "pinning" / "overrides.yaml").read_text().splitlines():
        if line.startswith("#"):
            continue
        if line.startswith("  #"):
            comments.append(line)
        elif line.startswith("  ") and not line.startswith("   "):
            skip = line[2:].split(":")[0] in own
            if not skip:
                out += comments + [line]
            comments = []
        elif line.startswith("    "):
            if not skip:
                out.append(line)
        else:
            out.append(line)
    if own:
        out.append(f"  # ros-{distro} specific (distros/{distro}/distro.yaml)")
        for key, value in own.items():
            out.append(f"  {key}:")
            out += [f"    - {v}" for v in (value if isinstance(value, list) else [value])]
    return "\n".join(out) + "\n"


def render_tests(distro: str, dest: Path) -> None:
    """Copy shared/tests; *.jinja files are rendered for the distribution
    ([% if distro == "humble" %] ... [% endif %], [= distro =])."""
    import jinja2

    env = jinja2.Environment(
        block_start_string="[%", block_end_string="%]",
        variable_start_string="[=", variable_end_string="=]",
        comment_start_string="[#", comment_end_string="#]",
        keep_trailing_newline=True, trim_blocks=True, lstrip_blocks=True,
        undefined=jinja2.StrictUndefined,
    )
    for src in sorted((SHARED / "tests").rglob("*")):
        if not src.is_file():
            continue
        rel = src.relative_to(SHARED / "tests")
        target = dest / str(rel).removesuffix(".jinja")
        target.parent.mkdir(parents=True, exist_ok=True)
        if src.suffix == ".jinja":
            target.write_text(env.from_string(src.read_text()).render(distro=distro))
        else:
            shutil.copy2(src, target)


# vinca.yaml keys whose lists are combined from shared/ and the distribution
LIST_KEYS = ("packages_select_by_deps", "packages_skip_by_deps", "packages_remove_from_deps")


def load_yaml(path: Path) -> dict:
    import yaml

    return (yaml.safe_load(path.read_text()) or {}) if path.is_file() else {}


def dump_yaml(data: dict, path: Path, source: str) -> None:
    import yaml

    header = f"# Generated by `pixi run rs <distro> prepare` from {source}; edit those instead.\n"
    path.write_text(header + yaml.safe_dump(data, sort_keys=False, width=1000))


def merge_vinca(shared: dict, own: dict) -> dict:
    merged = dict(shared)
    for key, value in own.items():
        if key in LIST_KEYS:
            seen, items = set(), []
            for item in (shared.get(key) or []) + (value or []):
                marker = json.dumps(item, sort_keys=True)
                if marker not in seen:
                    seen.add(marker)
                    items.append(item)
            merged[key] = items
        else:
            merged[key] = value
    return merged


def merge_entries(shared: dict, own: dict) -> dict:
    """Per-package files: the distribution's keys of an entry win over the shared ones."""
    merged = {k: (dict(v) if isinstance(v, dict) else v) for k, v in shared.items()}
    for key, value in own.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = {**merged[key], **value}
        else:
            merged[key] = value
    return merged


def work_dir(distro: str) -> Path:
    return DISTROS / distro / "work"


def prepare(distro: str) -> Path:
    """Assemble distros/<d>/work/ (keeps recipes/ and output/ of earlier runs)."""
    d, w = DISTROS / distro, work_dir(distro)
    w.mkdir(exist_ok=True)
    for name in ("patch", "tests"):
        shutil.rmtree(w / name, ignore_errors=True)

    vinca = merge_vinca(load_yaml(SHARED / "vinca.yaml"), load_yaml(d / "vinca.yaml"))
    vinca.update(
        conda_index=["robostack.yaml", "packages-ignore.yaml"],
        patch_dir="patch",
        rosdistro_snapshot="../rosdistro_snapshot.yaml",
        rosdistro_additional_recipes="../rosdistro_additional_recipes.yaml",
    )
    vinca.setdefault("skip_existing", [channel_url(distro) + "/"])
    dump_yaml(vinca, w / "vinca.yaml", f"shared/vinca.yaml and distros/{distro}/vinca.yaml")
    dump_yaml(
        merge_entries(load_yaml(SHARED / "pkg_additional_info.yaml"), load_yaml(d / "pkg_additional_info.yaml")),
        w / "pkg_additional_info.yaml",
        f"shared/pkg_additional_info.yaml and distros/{distro}/pkg_additional_info.yaml",
    )
    shutil.copytree(d / "patch", w / "patch", ignore=shutil.ignore_patterns("dependencies.yaml"))
    dump_yaml(
        merge_entries(load_yaml(SHARED / "dependencies.yaml"), load_yaml(d / "patch" / "dependencies.yaml")),
        w / "patch" / "dependencies.yaml",
        f"shared/dependencies.yaml and distros/{distro}/patch/dependencies.yaml",
    )
    render_tests(distro, w / "tests")
    for name in ("robostack.yaml", "packages-ignore.yaml"):
        shutil.copy2(SHARED / name, w / name)
    # vinca-gha inlines ./.scripts/build_win.bat into the Windows workflow (and falls
    # back to an outdated built-in script without it)
    shutil.rmtree(w / ".scripts", ignore_errors=True)
    shutil.copytree(ROOT / ".scripts", w / ".scripts")
    (w / "vinca_pinning.yaml").write_text(vinca_pinning(distro))
    if (d / "conda_build_config.yaml").is_file():
        shutil.copy2(d / "conda_build_config.yaml", w / "conda_build_config.yaml")
    return w


