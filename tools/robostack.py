# generated files
# --------------------------------------------------------------------------- #
def vinca_pinning(distro: str) -> str:
    """shared/pinning/conda_forge.yaml + overrides.yaml, adjusted by distro.yaml.

    Shared override entries that the distribution overrides itself are left out
    together with the comment lines above them (comments carry the conda-build
    selectors, so this works on text, not on parsed YAML).
    """
    s = settings(distro)
    own = s.get("pinning_overrides") or {}
    out = [f"# Generated by `pixi run rs {distro} render-pinning` from shared/pinning/ and",
           f"# distros/{distro}/distro.yaml; edit those instead.", ""]
    if s.get("conda_forge_pinning_version"):
        out.append(f"conda_forge_pinning_version: {s['conda_forge_pinning_version']}")
        out.append("migrations:")
        out += [f"  - {m}" for m in s.get("conda_forge_migrations") or []]
    else:
        out += [l for l in (SHARED / "pinning" / "conda_forge.yaml").read_text().splitlines()
                if not l.startswith("#")]
    comments: list[str] = []
    skip = False
    for line in (SHARED / "pinning" / "overrides.yaml").read_text().splitlines():
        if line.startswith("#"):
            continue
        if line.startswith("  #"):
            comments.append(line)
        elif line.startswith("  ") and not line.startswith("   "):
            skip = line[2:].split(":")[0] in own
            if not skip:
                out += comments + [line]
            comments = []
        elif line.startswith("    "):
            if not skip:
                out.append(line)
        else:
            out.append(line)
    if own:
        out.append(f"  # ros-{distro} specific (distros/{distro}/distro.yaml)")
        for key, value in own.items():
            out.append(f"  {key}:")
            out += [f"    - {v}" for v in (value if isinstance(value, list) else [value])]
    return "\n".join(out) + "\n"


def render_tests(distro: str, dest: Path) -> None:
    """Copy shared/tests; *.jinja files are rendered for the distribution
    ([% if distro == "humble" %] ... [% endif %], [= distro =])."""
    import jinja2

    env = jinja2.Environment(
        block_start_string="[%", block_end_string="%]",
        variable_start_string="[=", variable_end_string="=]",
        comment_start_string="[#", comment_end_string="#]",
        keep_trailing_newline=True, trim_blocks=True, lstrip_blocks=True,
        undefined=jinja2.StrictUndefined,
    )
    for src in sorted((SHARED / "tests").rglob("*")):
        if not src.is_file():
            continue
        rel = src.relative_to(SHARED / "tests")
        target = dest / str(rel).removesuffix(".jinja")
        target.parent.mkdir(parents=True, exist_ok=True)
        if src.suffix == ".jinja":
            target.write_text(env.from_string(src.read_text()).render(distro=distro))
        else:
            shutil.copy2(src, target)


def prepare(distro: str) -> None:
    d = DISTROS / distro
    tests = d / "tests"
    if tests.exists():
        shutil.rmtree(tests)
    render_tests(distro, tests)
    (d / "vinca_pinning.yaml").write_text(vinca_pinning(distro))


