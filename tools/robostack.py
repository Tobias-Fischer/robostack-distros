"""Run a RoboStack task for one distribution of this repository.

    pixi run rs <distro> <task> [args...]
    pixi run rs jazzy generate-recipes
    pixi run rs jazzy build-one ros2-ros-workspace
    pixi run rs changed-distros --base origin/main      # for CI
    pixi run rs check | update-pinning | new-distro NAME --from DISTRO   (whole repository)

Every distribution lives in distros/<distro>/ and only holds what is specific to
it; everything else is in shared/. Tasks run in distros/<distro>/work/ (generated,
git-ignored), which `prepare` assembles from both:

- vinca.yaml               shared/vinca.yaml + distros/<d>/vinca.yaml (lists are
                           concatenated, other keys from the distribution win)
- pkg_additional_info.yaml shared/ + distros/<d>/ (per package; the distribution's
                           keys win, e.g. its build_number)
- patch/                   distros/<d>/patch/, with patch/dependencies.yaml merged
                           from shared/dependencies.yaml like pkg_additional_info
- tests/                   shared/tests (*.jinja rendered for the distribution)
- robostack.yaml, packages-ignore.yaml, vinca_pinning.yaml, conda_build_config.yaml

rosdistro_snapshot.yaml and rosdistro_additional_recipes.yaml are read from
distros/<d>/ directly; conda_build_config.yaml is rendered back into distros/<d>/
(committed) by `render-pinning`.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DISTROS = ROOT / "distros"
SHARED = ROOT / "shared"
TOOLS = ROOT / "tools"
CONDA_FORGE = "https://prefix.dev/conda-forge"

# Files whose change affects every distribution (anything outside distros/).
PER_DISTRO_PREFIX = "distros/"


def distros() -> list[str]:
    return sorted(p.name for p in DISTROS.iterdir() if (p / "vinca.yaml").is_file())


def settings(distro: str) -> dict:
    import yaml  # not needed for changed-distros, which runs without pixi in CI

    return yaml.safe_load((DISTROS / distro / "distro.yaml").read_text()) or {}


def channel_url(distro: str) -> str:
    s = settings(distro)
    name = s.get("channel_name", f"robostack-{distro}")
    if s.get("upload_target", "prefix") == "prefix":
        return f"https://prefix.dev/{name}"
    return f"https://conda.anaconda.org/{name}"


def run(cmd: list[str], cwd: Path) -> int:
    print("+", " ".join(cmd), f"  (in {cwd.relative_to(ROOT)})", flush=True)
    return subprocess.run(cmd, cwd=cwd).returncode


