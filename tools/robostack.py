def rattler_build(distro: str, args: list[str], skip_existing: bool = True) -> list[str]:
    cmd = ["rattler-build", "build", "-m", "./conda_build_config.yaml",
           "-c", channel_url(distro), "-c", CONDA_FORGE, "--channel-priority", "disabled"]
    return cmd + (["--skip-existing"] if skip_existing else []) + args


def task(distro: str, name: str, args: list[str]) -> int:
    d = DISTROS / distro
    py = [sys.executable]
    if name == "prepare":
        prepare(distro)
        return 0
    if name == "render-pinning":
        prepare(distro)
        return run(["vinca-pinning-render"], d)
    if name == "generate-recipes":
        prepare(distro)
        shutil.rmtree(d / "recipes", ignore_errors=True)
        shutil.rmtree(d / "recipes_only_patch", ignore_errors=True)
        (d / "recipes").mkdir()
        return run(["vinca", "-m", *args], d)
    if name == "check-orphaned-patches":
        return run(py + [str(TOOLS / "check_orphaned_platform_patches.py"), *args], d)
    if name == "check-patches":
        return run(py + [str(TOOLS / "check_patches_clean_apply.py"), *args], d)
    if name == "check-deps":
        return run(py + [str(TOOLS / "check_dependency_compat.py"), *args], d)
    if name == "gap-report":
        return run(py + [str(TOOLS / "build_gap_report.py"), *args], d)
    if name == "create-snapshot":
        return run(["vinca-snapshot", "-d", distro, "-o", "rosdistro_snapshot.yaml", *args], d)
    if name == "build":
        return run(rattler_build(distro, ["--recipe-dir", "./recipes", *args]), d)
    if name == "build-ci":  # used by .scripts/build_unix.sh / build_win.bat
        return run(rattler_build(distro, args, skip_existing=False), d)
    if name == "build-one":
        pkg = args[0] if args else "ros2-ros-workspace"
        for patch in (d / "patch").glob(f"{pkg}.*patch"):
            shutil.copy(patch, d / "recipes" / pkg / "patch" / patch.name)
        return run(rattler_build(distro, ["--recipe", f"./recipes/{pkg}/recipe.yaml", *args[1:]], False), d)
    if name == "upload":
        s = settings(distro)
        name_ = s.get("channel_name", f"robostack-{distro}")
        if s.get("upload_target", "prefix") == "prefix":
            cmd = ["rattler-build", "upload", "prefix", "-c", name_, "--generate-attestation", "--skip-existing"]
        else:
            cmd = ["rattler-build", "upload", "anaconda", "-o", name_, "-a", os.environ.get("ANACONDA_API_TOKEN", ""), "--force"]
        return run(cmd + args, d)
    if name == "sort":
        files = ["pkg_additional_info.yaml", "rosdistro_additional_recipes.yaml"]
        rc = run(["vinca-sort-vinca-lists", *args, "vinca.yaml"], d)
        return rc or run(["vinca-sort-yaml-keys", *args, *files], d)
    if name == "gha":  # staged build workflows for one platform, see .github/workflows/main.yml
        return generate_gha(distro, args)
    raise SystemExit(f"unknown task {name!r}")


def generate_gha(distro: str, args: list[str]) -> int:
    """vinca-gha for one distribution; the workflow gets a distro-specific name,
    trigger branch and file name, and tells the build scripts which distro to build."""
    parser = argparse.ArgumentParser(prog="rs <distro> gha")
    parser.add_argument("--platform", required=True)
    parser.add_argument("--batch-size", default="10")
    ns = parser.parse_args(args)
    d = DISTROS / distro
    branch = f"buildbranch_{distro}_{ns.platform.replace('-', '_')}"
    before = set(d.glob("*.yml"))
    rc = run(["vinca-gha", "--platform", ns.platform, "--trigger-branch", branch, "-d", "./recipes",
              "--batch_size", ns.batch_size], d)
    if rc:
        return rc
    import yaml

    for wf in sorted(set(d.glob("*.yml")) - before):
        data = yaml.safe_load(wf.read_text())
        data["name"] = f"{distro} {data.get('name', wf.stem)}"
        data["env"] = {**(data.get("env") or {}), "ROBOSTACK_DISTRO": distro}
        dest = ROOT / ".github" / "workflows" / f"build_{distro}_{wf.stem}.yml"
        dest.write_text(yaml.safe_dump(data, sort_keys=False, width=1000))
        wf.unlink()
        print(f"wrote {dest.relative_to(ROOT)} (trigger branch {branch})")
    return 0


def changed_distros(base: str) -> list[str]:
    out = subprocess.run(["git", "diff", "--name-only", f"{base}...HEAD"], cwd=ROOT,
                         capture_output=True, text=True, check=True).stdout.split()
    out = [f for f in out if not f.endswith(".md") and f != "LICENSE"]  # docs don't need builds
    if any(not f.startswith(PER_DISTRO_PREFIX) for f in out):
        return distros()  # shared files changed: every distribution is affected
    return sorted({f.split("/")[1] for f in out if f.count("/") >= 2} & set(distros()))


def main() -> int:
    if len(sys.argv) >= 2 and sys.argv[1] == "changed-distros":
        parser = argparse.ArgumentParser(prog="rs changed-distros")
        parser.add_argument("--base", required=True)
        parser.add_argument("--all", action="store_true", help="ignore the diff, list every distribution")
        ns = parser.parse_args(sys.argv[2:])
        print(json.dumps(distros() if ns.all else changed_distros(ns.base)))
        return 0
    if len(sys.argv) < 3:
        print(__doc__)
        print("distributions:", ", ".join(distros()))
        return 2
    distro, name, *args = sys.argv[1:]
    if distro not in distros():
        raise SystemExit(f"unknown distribution {distro!r}; choose from {', '.join(distros())}")
    return task(distro, name, args)


if __name__ == "__main__":
    sys.exit(main())
